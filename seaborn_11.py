import seaborn as sns
import matplotlib.pyplot as plt
import pandas as pd

df = pd.DataFrame({
    'Food Category': ['Pizza', 'Burger', 'Biryani', 'Momos', 'Ice Cream'],
    'Orders': [120, 150, 180, 90, 75]
})

sns.set_theme(style='whitegrid')

plt.figure(figsize=(8, 5))
sns.barplot(data=df, x='Food Category', y='Orders', color='skyblue')

plt.title('Orders by Food Category')
plt.xlabel('Food Category')
plt.ylabel('Number of Orders')
plt.savefig('food_orders.png', dpi=300, bbox_inches='tight')
plt.show()

df = pd.DataFrame({
    'Day': ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'],
    'Steps': [4500, 6000, 5200, 7500, 8000, 10000, 9000]
})

sns.set_theme(style='whitegrid', palette='muted')

plt.figure(figsize=(9, 5))
sns.lineplot(data=df, x='Day', y='Steps', marker='o')

plt.title('Daily Step Counts')
plt.xlabel('Day')
plt.ylabel('Number of Steps')
plt.savefig('daily_steps.svg', format='svg', bbox_inches='tight')
plt.show()

df = pd.DataFrame({
    'Product': ['Mobile', 'Laptop', 'Tablet', 'Headphones', 'Watch'],
    'Sales': [250, 180, 120, 200, 150]
})

sns.set_theme(style='darkgrid', palette='colorblind')

plt.figure(figsize=(8, 5))
sns.barplot(data=df, x='Product', y='Sales', hue='Product', legend=False)

plt.title('Product Sales Analysis')
plt.xlabel('Product')
plt.ylabel('Number of Sales')
plt.xticks(rotation=15)
plt.savefig('darkgrid_sales.png', dpi=1200, bbox_inches='tight')
plt.show()

def apply_presentation_theme():
    sns.set_theme(
        style='whitegrid',
        context='talk',
        palette='deep',
        font='DejaVu Sans',
        font_scale=1.0
    )
apply_presentation_theme()

apps = ['WhatsApp', 'Instagram', 'YouTube', 'Spotify', 'Google Maps']
usage = [30, 25, 20, 15, 10]

plt.figure(figsize=(8, 7))

colors = sns.color_palette('deep', n_colors=5)

plt.pie(
    usage,
    labels=apps,
    autopct='%1.1f%%',
    startangle=90,
    colors=colors
)

plt.title('Top 5 Most-Used Apps')
plt.tight_layout()
plt.savefig('top_apps_pie.png', dpi=300, bbox_inches='tight')
plt.show()

df = pd.DataFrame({
    'Delivery Time': [25, 30, 35, 40, 45],
    'Order Amount': [200, 350, 300, 500, 450],
    'Rating': [4.5, 4.2, 4.0, 3.8, 3.5],
    'Distance': [2, 4, 5, 7, 9]
})

corr = df.corr()

sns.set_theme(style='white')
plt.figure(figsize=(8, 6))

sns.heatmap(
    corr,
    annot=True,
    cmap='coolwarm',
    fmt='.2f',
    linewidths=0.5
)

plt.title('Food Delivery Data Correlation Heatmap')
plt.savefig(
    'correlation_heatmap.svg',
    format='svg',
    dpi=1200,
    bbox_inches='tight'
)

plt.show()